"""새 공고 신청 기간 글 읽기(app.catalog.period.parse_period)와 보여 줄 때 앞머리 기호 떼기."""
from datetime import date

import pytest

from app.catalog.period import parse_period
from app.catalog.texts import plain_line, plain_lines

READ = date(2026, 11, 14)


@pytest.mark.parametrize("text, start, end", [
    ("가. 신청기간: 2026. 11. 9.(월) ~ 11. 23.(월) (15일간)", date(2026, 11, 9), date(2026, 11, 23)),
    ("3. 신청기간: 2026. 11. 10.(화) ~ 12. 4.(금) * 근무시간 내에 한함", date(2026, 11, 10), date(2026, 12, 4)),
    ("가. 신청기한: 2026. 11. 2(월)~ 2026. 12. 31.(목)까지", date(2026, 11, 2), date(2026, 12, 31)),
    ("2026.11.9.~11.23.", date(2026, 11, 9), date(2026, 11, 23)),
    ("11. 10.(화) ~ 12. 4.(금)", date(2026, 11, 10), date(2026, 12, 4)),                 # 연도 없음: 읽은 날의 해
    ("12. 20. ~ 1. 10.", date(2026, 12, 20), date(2027, 1, 10)),                          # 끝이 앞서면 다음 해
    ("2026. 12. 20. ~ 2027. 1. 10.", date(2026, 12, 20), date(2027, 1, 10)),
    ("11월 9일 ~ 11월 23일", date(2026, 11, 9), date(2026, 11, 23)),
    ("~ 12. 31.까지", None, date(2026, 12, 31)),                                         # 끝만
    ("12. 31.(목)까지", None, date(2026, 12, 31)),
    ("11. 20.부터", date(2026, 11, 20), None),
])
def test_known_shapes(text, start, end):
    assert parse_period(text, READ) == (start, end)


@pytest.mark.parametrize("text", [
    "연중 상시", "", "   ", "예산 소진 시까지", "2026. 2. 30. ~ 3. 4.", "2026. 13. 1. ~ 2026. 13. 5.",   # 달력에 없는 날
    "11. 9. 11. 23.",                                  # 이어 주는 말이 없다
    "1차 11. 1. ~ 11. 10., 2차 11. 20. ~ 11. 30.",      # 날짜가 셋 이상: 어느 것이 마감인지 알 수 없다
    "2026. 11. 9.",                                    # 하나뿐이고 시작인지 끝인지 모른다
    "1. 5.까지",                                       # 연도 없는 끝 날짜가 읽은 날보다 앞: 해를 모른다
    "근무시간 9:00 ~ 18:00",
    "2027. 10. 15.(목) ~ 11. 30.",                     # 시작이 반년 넘게 앞선 미래: 해 오타일 수 있어 읽지 않는다(서귀포시 융복합 융자 원문)
])
def test_unreadable_shapes_are_none(text):
    assert parse_period(text, READ) == (None, None)


def test_end_before_start_with_explicit_years_is_not_guessed():
    assert parse_period("2026. 12. 20. ~ 2026. 11. 1.", READ) == (None, None)


def test_plain_line_drops_only_leading_marks():
    cases = {"가. 신청기간: 2026. 11. 9.": "신청기간: 2026. 11. 9.", "3. 신청기간: x": "신청기간: x", "○ 유기농업자재": "유기농업자재",
             "- 유기질비료(3종)": "유기질비료(3종)", "※ 농외소득 3,700만원": "농외소득 3,700만원", "* 2026년 토양검정": "2026년 토양검정",
             "다. 지원내용": "지원내용", "① 인증사업자": "인증사업자", "- ※ 겹친 기호": "겹친 기호", "11. 10.(화) ~ 12. 4.(금)": "11. 10.(화) ~ 12. 4.(금)",
             "접수처: 지역 농·감협": "접수처: 지역 농·감협", "": ""}
    for raw, shown in cases.items():
        assert plain_line(raw) == shown, raw
    assert plain_lines("5. 지원기준: 가\n\n4. 지원일수: 나") == ("지원기준: 가", "지원일수: 나")


@pytest.mark.parametrize("text, end", [
    # 맞춰 보기 모듈이 따로 가졌던 notice_end_date 의 사례(같은 입력에 같은 끝 날짜가 나와야 한다)
    ("가. 신청기간: 2026. 11. 9.(월) ~ 11. 23.(월) (15일간)", date(2026, 11, 23)),
    ("가. 신청기한: 2026. 11. 2(월)~ 2026. 12. 31.(목)까지", date(2026, 12, 31)),
    ("3. 신청기간: 2026. 11. 10.(화) ~ 12. 4.(금) * 근무시간 내에 한함", date(2026, 12, 4)),
    ("2026. 12. 20. ~ 2027. 1. 5.", date(2027, 1, 5)),
    ("2026. 12. 20. ~ 1. 5.", date(2027, 1, 5)),
    ("2026. 12. 31.까지", date(2026, 12, 31)),
    ("2026. 11. 9.(월) ~ 11. 23.(월) 지원한도 1.5억", date(2026, 11, 23)),               # 금액 소수('1.5억')는 날짜가 아니다
    ("2026. 11. 9.(월) ~ 11. 23.(월) (15일간) 한도 1.5억 원", date(2026, 11, 23)),
    ("2026. 12. 20. ~ 2027. 1. 10. 지원 3.5톤", date(2027, 1, 10)),
    ("지원한도 1.5억, 2026. 12. 31.까지", date(2026, 12, 31)),
    ("2026. 12. 31.까지 지원한도 1.5억", date(2026, 12, 31)),
    ("1. 신청기간: 연중 상시 모집", None),
    ("", None),
    ("2026. 2. 31. ~ 2026. 2. 30.", None),
    ("2026. 11. 9. ~ 11. 8.", None),                    # 같은 달에서 끝이 시작보다 이르면 읽지 않는다
    ("2026. 11. 9. ~ 1.5억", None),
])
def test_end_date_cases_moved_from_match_module(text, end):
    assert parse_period(text, READ)[1] == end


def test_year_less_period_is_read_with_the_read_date_year():
    """전 맞춰 보기 모듈은 연도 없는 글을 읽지 않았다. 지금은 읽은 날의 해로 읽는다(합치며 달라진 한 가지)."""
    assert parse_period("신청기간: 11. 9. ~ 11. 23.", READ) == (date(2026, 11, 9), date(2026, 11, 23))


def test_money_decimal_is_not_counted_as_a_third_date():
    assert parse_period("2026. 11. 9.(월) ~ 11. 23.(월) 지원한도 1.5억", READ) == (date(2026, 11, 9), date(2026, 11, 23))
