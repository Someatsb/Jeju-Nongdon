"""{P:id}를 이름으로 채울 때 뒤따르는 조사를 받침에 맞춘다(실호출 P4: '건강보험료 지원는')."""
import pytest

from app.agents.counsel import fill_placeholders

NAMES = {"a": "농어업인 건강보험료 지원", "b": "제주형 가격안정관리제", "c": "농민수당", "d": "농작물보험(양배추)",
         "e": "농작물보험(양파)", "f": "NH안전보험", "g": "소농직불금", "h": "예산(2026)"}


@pytest.mark.parametrize("text, want", [
    ("{P:a}는 가입 방식을 확인", "농어업인 건강보험료 지원은 가입 방식을 확인"),
    ("{P:a}가 있습니다", "농어업인 건강보험료 지원이 있습니다"),
    ("{P:b}을 알아보세요", "제주형 가격안정관리제를 알아보세요"),
    ("{P:a}과 같이", "농어업인 건강보험료 지원과 같이"),                 # 받침 있음: 그대로
    ("{P:b}과 같이", "제주형 가격안정관리제와 같이"),
    ("{P:c}로 신청", "농민수당으로 신청"),
    ("{P:b}으로 신청", "제주형 가격안정관리제로 신청"),
    ("{P:g}로 신청", "소농직불금으로 신청"),                              # ㅁ 받침: 으로
    ("{P:d}는 좋습니다", "농작물보험(양배추)는 좋습니다"),                 # 괄호 안 마지막 글자 '추' 받침 없음
    ("{P:e}는 좋습니다", "농작물보험(양파)는 좋습니다"),
    ("{P:d}이 있고", "농작물보험(양배추)가 있고"),
    ("{P:a}입니다", "농어업인 건강보험료 지원입니다"),                     # 조사가 아닌 말은 건드리지 않는다
    ("{P:a}은행", "농어업인 건강보험료 지원은행"),
    ("{P:f}는 확인", "NH안전보험은 확인"),
    ("{P:h}는 확인", "예산(2026)는 확인"),                                # 끝이 숫자 괄호면 모르니 그대로
    ("{P:zz}는 확인", "{P:zz}는 확인"),
])
def test_josa_follows_filled_name(text, want):
    assert fill_placeholders(text, NAMES) == want
